package dev.homecloud.android.identity

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.io.IOException
import java.security.GeneralSecurityException
import java.security.KeyStore
import java.security.ProviderException
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Signals that the protected key material could not be encrypted, decrypted or read. */
internal class IdentityStorageException(
    message: String,
    cause: Throwable? = null,
) : Exception(message, cause)

internal interface IdentityCipher {
    /** Returns iv || ciphertext for [plaintext]. */
    fun encrypt(plaintext: ByteArray): ByteArray

    /** Reverses [encrypt]; throws [IdentityStorageException] on any failure. */
    fun decrypt(payload: ByteArray): ByteArray
}

/**
 * AES-256-GCM envelope over a caller-supplied key (`FR-AND-026 / 2`).
 *
 * [seal] returns the 12-byte IV generated by the cipher followed by the ciphertext. [open] splits
 * that IV from the payload and authenticates the ciphertext with its 128-bit tag. The transformation
 * is requested without a provider name, so the envelope is independent of where the key came from.
 * Failures never expose key material or plaintext.
 */
internal object AesGcmSealer {
    /** Returns iv || ciphertext for [plaintext] under [key]. */
    fun seal(
        key: SecretKey,
        plaintext: ByteArray,
    ): ByteArray =
        try {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.ENCRYPT_MODE, key)
            val iv = cipher.iv
            if (iv.size != IV_BYTES) {
                throw IdentityStorageException(ENCRYPTION_FAILED_MESSAGE)
            }
            iv + cipher.doFinal(plaintext)
        } catch (exception: GeneralSecurityException) {
            throw IdentityStorageException(ENCRYPTION_FAILED_MESSAGE, exception)
        }

    /** Reverses [seal]; throws [IdentityStorageException] on short input or failed authentication. */
    fun open(
        key: SecretKey,
        payload: ByteArray,
    ): ByteArray {
        if (payload.size < IV_BYTES + TAG_BYTES) {
            throw IdentityStorageException(DECRYPTION_FAILED_MESSAGE)
        }
        return try {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(
                Cipher.DECRYPT_MODE,
                key,
                GCMParameterSpec(TAG_BITS, payload.copyOfRange(0, IV_BYTES)),
            )
            cipher.doFinal(payload, IV_BYTES, payload.size - IV_BYTES)
        } catch (exception: GeneralSecurityException) {
            throw IdentityStorageException(DECRYPTION_FAILED_MESSAGE, exception)
        }
    }

    private const val TRANSFORMATION = "AES/GCM/NoPadding"
    private const val IV_BYTES = 12
    private const val TAG_BITS = 128
    private const val TAG_BYTES = TAG_BITS / 8

    private const val ENCRYPTION_FAILED_MESSAGE = "Could not encrypt the installation identity"
    private const val DECRYPTION_FAILED_MESSAGE = "Could not decrypt the installation identity"
}

/**
 * AES-256-GCM under a non-exportable Android KeyStore key (`FR-AND-026 / 2`).
 *
 * The key is created on first use with encryption and decryption purposes, the GCM block mode,
 * no padding, no user-authentication requirement and randomised encryption. Sealing and opening a
 * payload are delegated to [AesGcmSealer]. Keystore key retrieval is the platform-specific part of
 * this class: Robolectric provides no AndroidKeyStore provider, so the envelope logic is covered by
 * [AesGcmSealer] on the JVM and the key retrieval is covered by inspection and instrumentation.
 * A missing KeyStore key never causes plaintext to be written, and failures never expose key
 * material or plaintext.
 */
internal class KeystoreIdentityCipher : IdentityCipher {
    override fun encrypt(plaintext: ByteArray): ByteArray =
        try {
            AesGcmSealer.seal(encryptionKey(), plaintext)
        } catch (exception: GeneralSecurityException) {
            throw IdentityStorageException(ENCRYPTION_FAILED_MESSAGE, exception)
        } catch (exception: ProviderException) {
            throw IdentityStorageException(ENCRYPTION_FAILED_MESSAGE, exception)
        } catch (exception: IOException) {
            throw IdentityStorageException(ENCRYPTION_FAILED_MESSAGE, exception)
        }

    override fun decrypt(payload: ByteArray): ByteArray =
        try {
            AesGcmSealer.open(decryptionKey(), payload)
        } catch (exception: GeneralSecurityException) {
            throw IdentityStorageException(DECRYPTION_FAILED_MESSAGE, exception)
        } catch (exception: ProviderException) {
            throw IdentityStorageException(DECRYPTION_FAILED_MESSAGE, exception)
        } catch (exception: IOException) {
            throw IdentityStorageException(DECRYPTION_FAILED_MESSAGE, exception)
        }

    private fun encryptionKey(): SecretKey {
        val keyStore = keyStore()
        return existingKey(keyStore) ?: generateKey()
    }

    private fun decryptionKey(): SecretKey {
        val keyStore = keyStore()
        return existingKey(keyStore) ?: throw IdentityStorageException(DECRYPTION_FAILED_MESSAGE)
    }

    private fun existingKey(keyStore: KeyStore): SecretKey? = keyStore.getKey(KEY_ALIAS, null) as? SecretKey

    private fun generateKey(): SecretKey {
        val generator = KeyGenerator.getInstance(KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        generator.init(
            KeyGenParameterSpec
                .Builder(KEY_ALIAS, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(KEY_SIZE_BITS)
                .setUserAuthenticationRequired(false)
                .setRandomizedEncryptionRequired(true)
                .build(),
        )
        return generator.generateKey()
    }

    private fun keyStore(): KeyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null, null) }

    private companion object {
        const val ANDROID_KEYSTORE = "AndroidKeyStore"
        const val KEY_ALIAS = "homecloud-installation-identity"
        const val KEY_ALGORITHM_AES = KeyProperties.KEY_ALGORITHM_AES
        const val KEY_SIZE_BITS = 256

        const val ENCRYPTION_FAILED_MESSAGE = "Could not encrypt the installation identity"
        const val DECRYPTION_FAILED_MESSAGE = "Could not decrypt the installation identity"
    }
}
